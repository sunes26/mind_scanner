const YEAR = 2026
const MONTH = 9

function formatTime(totalMinutes) {
  const wrapped = ((totalMinutes % 1440) + 1440) % 1440
  const hour24 = Math.floor(wrapped / 60)
  const minute = wrapped % 60
  const period = hour24 < 12 ? '오전' : '오후'
  const hour12 = hour24 % 12 === 0 ? 12 : hour24 % 12
  return `${period} ${hour12}:${String(minute).padStart(2, '0')}`
}

const lines = [`${A} 님과 카카오톡 대화`, `저장한 날짜 : ${YEAR}년 ${MONTH}월 22일 오전 10:00`, '']
let messageCount = 0

for (const [day, start, messages] of scenes) {
  const [startHour, startMinute] = start.split(':').map(Number)
  let clock = startHour * 60 + startMinute
  let currentDay = day
  for (const [sender, text, gap] of messages) {
    clock += gap
    if (clock >= 1440) {
      clock -= 1440
      currentDay += 1
    }
    lines.push(`${YEAR}년 ${MONTH}월 ${currentDay}일 ${formatTime(clock)}, ${sender} : ${text}`)
    messageCount += 1
  }
}

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const text = lines.join('\n') + '\n'

mkdirSync(join(root, 'public', 'sample'), { recursive: true })
writeFileSync(join(root, 'public', 'sample', 'sample-chat.txt'), text, 'utf8')

mkdirSync(join(root, 'data'), { recursive: true })
writeFileSync(
  join(root, 'data', 'sampleChat.ts'),
  `// scripts/generate-sample-chat.mjs 가 만든 파일. 직접 수정하지 말 것.\n// 등장인물과 내용은 모두 가상이다.\nexport const SAMPLE_CHAT_TEXT = ${JSON.stringify(text)}\n`,
  'utf8',
)

process.stdout.write(`sample chat generated: ${messageCount} messages\n`)
